const PrescriptionService = require('../services/PrescriptionService');

class PrescriptionController {
    constructor() { this.service = new PrescriptionService(); }

    getAllPrescriptions = async (req, res) => {
        try {
            const items = await this.service.getAll();
            res.json(items);
        } catch (err) {
            res.status(500).json({ error: err.message });
        }
    };

    getPrescriptionById = async (req, res) => {
        try {
            const item = await this.service.getById(req.params.id);
            res.json(item);
        } catch (err) {
            res.status(500).json({ error: err.message });
        }
    };

    getPrescriptionsByDoctor = async (req, res) => {
        try {
            const items = await this.service.getAllByDoctor(req.params.doctor_id);
            res.json(items);
        } catch (err) {
            res.status(500).json({ error: err.message });
        }
    };

    createPrescription = async (req, res) => {
        try {
            const created = await this.service.create(req.body);
            res.json(created);
        } catch (err) {
            res.status(500).json({ error: err.message });
        }
    };

    updatePrescription = async (req, res) => {
        try {
            const result = await this.service.update(req.params.id, req.body);
            res.json(result);
        } catch (err) {
            res.status(500).json({ error: err.message });
        }
    };

    deletePrescription = async (req, res) => {
        try {
            const result = await this.service.delete(req.params.id);
            res.json(result);
        } catch (err) {
            res.status(500).json({ error: err.message });
        }
    };
}

module.exports = PrescriptionController;
